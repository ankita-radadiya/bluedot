import {
  getCustomerSubscriptionStatus,
  updateCustomerSubscription,
} from './api/graphql.js';
import { showNotification } from '../../scripts/components/notification.js';
import { readBlockConfig } from '../../scripts/aem.js';

/**
 * Checks if the block configuration specifies a minified view.
 * Handles block table key-value rows, CSS block classes, and dataset attributes.
 *
 * @param {HTMLElement} block
 * @returns {boolean}
 */
function checkIsMinified(block) {
  // 1. Check block CSS classes (e.g., class="commerce-newsletter minified")
  if (block.classList.contains('minified')) {
    return true;
  }

  // 2. Check HTML data attributes (e.g., data-minified="true")
  if (block.dataset?.minified === 'true' || block.getAttribute('data-minified') === 'true') {
    return true;
  }

  // 3. Read block configuration key-value rows generated by the authoring table
  try {
    const config = readBlockConfig(block);
    const minifiedVal = config.minified || config['minified-view'] || config.minifiedview;
    if (minifiedVal !== undefined) {
      const strVal = String(minifiedVal).trim().toLowerCase();
      return strVal === 'true' || strVal === 'yes' || strVal === '1';
    }
  } catch (err) {
    // Fallback if readBlockConfig is unavailable
  }

  return false;
}

/**
 * Decorates the ACCS newsletter component block for logged-in users.
 * @param {HTMLElement} block
 */
export default async function decorate(block) {
  const isMinified = checkIsMinified(block);

  try {
    const isSubscribed = await getCustomerSubscriptionStatus();

    if (isMinified) {
      renderMinifiedView(block, isSubscribed);
    } else {
      renderFullView(block, isSubscribed);
    }
  } catch {
    block.innerHTML = `
      <div class="newsletter-unauthorized">
        <p>Please <a href="/customer/login">log in</a> to manage your newsletter subscriptions.</p>
      </div>
    `;
  }
}

/**
 * Renders the Minified Dashboard Widget View
 */
function renderMinifiedView(container, isSubscribed) {
  const statusText = isSubscribed
    ? 'You are subscribed to "General Subscription".'
    : 'You are not subscribed to any newsletter.';

  container.innerHTML = `
    <div class="newsletter-card">
      <div class="newsletter-card-header">
        <h2 class="newsletter-card-header-title">Newsletter</h2>
      </div>
      <div class="newsletter-card-body">
      <p>${statusText}</p>
      <a href="/customer/newsletter" class="newsletter-edit-btn">
        <svg class="edit-icon" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
          <path d="M11 4H4a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7"></path>
          <path d="M18.5 2.5a2.121 2.121 0 0 1 3 3L12 15l-4 1 1-4 9.5-9.5z"></path>
        </svg>
        Edit
      </a>
      </div>
    </div>
  `;
}

/**
 * Renders the Full Newsletter Management View
 */
function renderFullView(container, initialSubscribedState) {
  container.innerHTML = `
    <div class="newsletter-full-container">
      <form class="newsletter-manage-form">
        <h2 class="newsletter-card-header-title">Subscription option</h2>
        <div class="newsletter-checkbox-group">
          <label class="newsletter-checkbox-label">
            <input 
              type="checkbox" 
              class="newsletter-checkbox"
              ${initialSubscribedState ? 'checked' : ''}
            />
            <span>General Subscription</span>
          </label>
        </div>
        <button type="submit" class="newsletter-save-btn">SAVE</button>
      </form>
    </div>
  `;

  const form = container.querySelector('.newsletter-manage-form');
  const checkbox = form.querySelector('.newsletter-checkbox');
  const saveBtn = form.querySelector('.newsletter-save-btn');

  form.addEventListener('submit', async (e) => {
    e.preventDefault();

    saveBtn.disabled = true;
    saveBtn.textContent = 'SAVING...';

    try {
      const isSubscribed = checkbox.checked;
      await updateCustomerSubscription(isSubscribed);

      const message = isSubscribed
        ? 'We saved the subscription status.'
        : 'You have unsubscribed from General Subscription.';

      showNotification({
        type: 'success',
        message,
      });
    } catch (error) {
      showNotification({
        type: 'error',
        message: error.message || 'Could not update subscription status.',
      });
    } finally {
      saveBtn.disabled = false;
      saveBtn.textContent = 'SAVE';
    }
  });
}
